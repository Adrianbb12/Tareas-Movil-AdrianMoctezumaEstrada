-- Run once in Supabase Dashboard > SQL Editor.
create table if not exists public.favorite_places (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  name text not null check (char_length(name) between 1 and 100),
  category text not null,
  description text not null default '',
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  photo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists favorite_places_user_created_idx
  on public.favorite_places (user_id, created_at desc);

alter table public.favorite_places enable row level security;
drop policy if exists "Owners can read their places" on public.favorite_places;
drop policy if exists "Owners can add their places" on public.favorite_places;
drop policy if exists "Owners can edit their places" on public.favorite_places;
drop policy if exists "Owners can delete their places" on public.favorite_places;

create policy "Owners can read their places" on public.favorite_places
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Owners can add their places" on public.favorite_places
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Owners can edit their places" on public.favorite_places
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Owners can delete their places" on public.favorite_places
  for delete to authenticated using ((select auth.uid()) = user_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('place-photos', 'place-photos', false, 10485760, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = false, file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Owners can read their place photos" on storage.objects;
drop policy if exists "Owners can upload their place photos" on storage.objects;
drop policy if exists "Owners can delete their place photos" on storage.objects;
create policy "Owners can read their place photos" on storage.objects
  for select to authenticated using (
    bucket_id = 'place-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "Owners can upload their place photos" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'place-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "Owners can delete their place photos" on storage.objects
  for delete to authenticated using (
    bucket_id = 'place-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
